/* Pre-renders the shared header and footer into every HTML page.
   Usage (from the site root):  node build/render.js
   Re-run after editing build/partials.js. Safe to run repeatedly:
   it replaces whatever sits between the site-header / site-footer markers. */
var fs=require('fs');
var path=require('path');
var partials=require('./partials');
var structuredData=require('./structured-data');

var ROOT=path.resolve(__dirname,'..');
var DIRS=['','services','destinations'];

function block(name, inner){
  return '<!-- '+name+':start (generated by build/render.js, do not edit by hand) -->\n'+
    inner+'\n<!-- '+name+':end -->';
}

// Matches either an already-rendered block or the original JS include
function pattern(name){
  return new RegExp('<!-- '+name+':start[\\s\\S]*?<!-- '+name+':end -->|<script src="(?:\\.\\./)?scripts/'+name+'\\.js"></script>');
}

var count=0;
DIRS.forEach(function(dir){
  fs.readdirSync(path.join(ROOT,dir)).filter(function(f){ return /\.html$/.test(f); }).forEach(function(f){
    var file=path.join(ROOT,dir,f);
    var page=(dir ? dir+'/' : '')+f;
    var R=dir ? '../' : '';
    var html=fs.readFileSync(file,'utf8');
    var out=html
      .replace(pattern('site-header'), function(){ return block('site-header', partials.header(R,page)); })
      .replace(pattern('site-footer'), function(){
        return block('site-footer', partials.footer(R)+'\n<script src="'+R+'scripts/site-footer.js"></script>');
      });
    // Structured data is built from the page's visible content, so it runs last
    var ld=block('structured-data', structuredData.build(out,page));
    out=/<!-- structured-data:start/.test(out)
      ? out.replace(/<!-- structured-data:start[\s\S]*?<!-- structured-data:end -->/, function(){ return ld; })
      : out.replace('</head>', function(){ return ld+'\n</head>'; });
    if(out!==html){ fs.writeFileSync(file,out); count++; }
  });
});
console.log('Rendered header, footer and structured data into '+count+' page(s).');
